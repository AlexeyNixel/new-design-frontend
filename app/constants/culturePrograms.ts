/**
 * Культурно-просветительские программы библиотеки (страница /test).
 *
 * Чтобы добавить программу — скопируйте объект целиком и поменяйте поля:
 *  - kind      — тип программы («Литературно-музыкальная программа», «Мастер-класс»…)
 *  - title     — название без кавычек-ёлочек, они добавятся сами
 *  - age       — возрастное ограничение (число: 12 → «12+»)
 *  - sessions  — даты и время: date в формате ГГГГ-ММ-ДД, время «ЧЧ:ММ»
 *  - price     — стоимость в рублях; 0 или null — «Вход свободный»
 *  - ticketUrl — ссылка «Приобрести билет»; если пусто — кнопка предложит позвонить
 *  - phone     — телефон отдела как в афише («218-27-34»), код города подставится сам
 */

export interface ProgramSession {
  /** ГГГГ-ММ-ДД */
  date: string;
  /** ЧЧ:ММ */
  start: string;
  /** ЧЧ:ММ */
  end?: string;
}

export interface CultureProgram {
  id: string;
  kind: string;
  title: string;
  age?: number;
  sessions: ProgramSession[];
  description: string;
  price?: number | null;
  ticketUrl?: string;
  department: string;
  phone?: string;
}

